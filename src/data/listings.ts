export function getListingById(id: string): ListingItem | undefined {
  return mockListings.find(listing => listing.id === id);
}

export function getRelatedListings(currentId: string, limit: number = 3): ListingItem[] {
  const current = getListingById(currentId);
  if (!current) return [];
  return mockListings
    .filter(l => l.id !== currentId && l.zone === current.zone)
    .slice(0, limit);
}
